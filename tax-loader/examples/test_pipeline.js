async function main() {
  ensureTmp();

  // Section 1: legacy TaxLoader
  for (const entityType of ENTITIES) {
    await testLegacyEntity(entityType);
    console.log(`[ok] TaxLoader   ${entityType}`);
  }

  // Section 2: new DrakeLoader
  for (const entityType of ENTITIES) {
    await testDrakeLoaderEntity(entityType);
    console.log(`[ok] DrakeLoader ${entityType}`);
  }

  // Section 3: DrakeLoader with 8949 + 4562 extras
  await testDrakeLoaderWith8949And4562();
  console.log('[ok] DrakeLoader  8949 + 4562');

  // Section 4: balance utility
  await testTrialBalanceBalance();
  console.log('[ok] Trial Balance balance check');

  console.log('\n✓ All tests passed');
}

main().catch(error => {
  console.error('[FAIL]', error.message);
  console.error(error.stack);
  process.exit(1);
});
